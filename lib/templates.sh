#!/usr/bin/env bash
# Template generation for Vulnotes CLI

TEMPLATES_DIR="$SCRIPT_DIR/templates"

generate_docker_compose() {
    local http_port="${1:-80}"
    local bind_address="${2:-127.0.0.1}"

    sed -e "s|{{HTTP_PORT}}|${http_port}|g" \
        -e "s|{{BIND_ADDRESS}}|${bind_address}|g" \
        "$TEMPLATES_DIR/docker-compose.yml.tmpl" > "$COMPOSE_FILE"
}

generate_nginx_conf() {
    cp "$TEMPLATES_DIR/nginx.conf.tmpl" "$INSTALL_DIR/nginx.conf"
}

generate_env_file() {
    local domain="$1"
    local jwt_secret="$2"
    local backronaut_secret="$3"
    local support_api_token="$4"
    local http_port="${5:-80}"

    # Compose DOMAIN with port so it matches the browser-sent Origin header.
    # Skip if the domain already includes a port, or if the port is the
    # scheme's default (80 for http, 443 for https).
    local domain_with_port="$domain"
    if [[ ! "$domain" =~ ^[a-zA-Z]+://[^/]+:[0-9]+ ]]; then
        local default_port=80
        [[ "$domain" =~ ^https:// ]] && default_port=443
        if [[ "$http_port" != "$default_port" ]]; then
            domain_with_port="${domain}:${http_port}"
        fi
    fi

    cat > "$ENV_FILE" << ENV_EOF
# Vulnotes Environment Configuration
# Generated by vulnotes-cli

DOMAIN=${domain_with_port}
JWT_SECRET=${jwt_secret}
BACKRONAUT_SECRET=${backronaut_secret}
SUPPORT_API_TOKEN=${support_api_token}
ENV_EOF

    chmod 600 "$ENV_FILE"
}
